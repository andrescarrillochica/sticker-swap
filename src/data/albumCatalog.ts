export type AlbumSection = (typeof albumSections)[number];

export type Sticker = {
  id: string;
  label: string;
  sectionCode: string;
  sectionName: string;
  group: string;
  number: number;
  type: "country" | "special";
};

export function generateStickersFromCatalog(): Sticker[] {
  return albumSections.flatMap((section) =>
    Array.from({ length: section.count }, (_, index) => {
      const number = index + 1;
      const paddedNumber = String(number).padStart(2, "0");

      return {
        id: `${section.code}-${paddedNumber}`,
        label: `${section.code} ${number}`,
        sectionCode: section.code,
        sectionName: section.name,
        group: section.group,
        number,
        type: section.type,
      };
    })
  );
}
